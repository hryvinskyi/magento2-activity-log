declare(strict_types=1);

namespace Hryvinskyi\ActivityLog\Test\Integration\Performance\Fixture;

use Hryvinskyi\ActivityLog\Model\ResourceModel\Activity as ActivityResource;
use Magento\Framework\App\ResourceConnection;

/**
 * A journal of a million activities over a year, with the record and field tables a module recording changes keeps
 *
 * The two side tables stand in for such a module's own: one row per change naming the record (type and id, both
 * strings, indexed together), and two or three field rows per change (field indexed with the activity id, values
 * unindexed, a few masked). The rows are generated by the database (MariaDB's SEQUENCE engine), outside any test
 * transaction, and removed afterwards: other tests empty the journal inside their transaction, which a million rows
 * would make slow.
 */
class PerformanceJournal
{
    public const ROWS = 1_000_000;
    public const NOW_MS = 1_950_000_000_000;
    public const SPAN_MS = 31_536_000_000;
    public const RECORD_TABLE = 'hryvinskyi_activity_log_test_record';
    public const FIELD_TABLE = 'hryvinskyi_activity_log_test_field';
    public const CORRELATION_PREFIX = 'perf-';
    public const CHANGE_CHANNEL = 'zz_change';
    public const RARE_PATH = 'alpha/beta/enabled';

    /**
     * @param ResourceConnection $resourceConnection
     */
    public function __construct(
        private readonly ResourceConnection $resourceConnection
    ) {
    }

    /**
     * Create the side tables and write the journal, unless a complete seed is already there
     *
     * @return void
     */
    public function seed(): void
    {
        $this->createSideTables();
        if ($this->seededRows() === self::ROWS) {
            return;
        }

        $this->remove();
        $this->createSideTables();
        $connection = $this->resourceConnection->getConnection();
        $journal = $this->journalTable();
        $stepMs = intdiv(self::SPAN_MS, self::ROWS);
        $firstMs = self::NOW_MS - self::ROWS * $stepMs;

        $connection->query(
            "INSERT INTO {$journal} (correlation_id, channel, action, subject_type, subject_id, subject_label,
                actor_type, actor_name, via_client, outcome, store_id, occurred_at_ms, created_at)
            SELECT CONCAT('" . self::CORRELATION_PREFIX . "', LPAD(FLOOR(seq / 3), 8, '0')),
                CASE WHEN seq % 20 < 8 THEN '" . self::CHANGE_CHANNEL . "' WHEN seq % 20 < 14 THEN 'zz_request'
                    WHEN seq % 20 < 19 THEN 'zz_api' ELSE 'zz_agent' END,
                ELT(1 + seq % 8, 'Item saved', 'Group saved', 'Setting saved', 'POST /items', 'GET /reports',
                    'Account saved', 'Page saved', 'run nightly_import.process'),
                'item', CAST(seq % 20000 + 1 AS CHAR), CONCAT('Item #', seq % 20000 + 1),
                ELT(1 + seq % 4, 'admin', 'admin', 'integration', 'cli'),
                ELT(1 + seq % 10, 'Jane Doe', 'John Smith', 'Ola Nordmann', 'ERP Sync', 'Mette Hansen',
                    'bin/magento', 'Lars Jensen', 'Anna Berg', 'PIM Feed', 'Karl Olsen'),
                IF(seq % 20 = 19, 'Desk Assistant', NULL),
                IF(seq % 50 = 0, 'failure', IF(seq % 97 = 0, 'denied', 'success')),
                IF(seq % 3 = 0, 1, 0),
                {$firstMs} + seq * {$stepMs},
                FROM_UNIXTIME(FLOOR(({$firstMs} + seq * {$stepMs}) / 1000))
            FROM seq_1_to_" . self::ROWS
        );

        $connection->query(
            'INSERT INTO ' . $this->table(self::RECORD_TABLE) . " (activity_id, record_type, record_id)
            SELECT entity_id,
                CASE WHEN entity_id % 10 < 6 THEN 'item' WHEN entity_id % 10 < 7 THEN 'group'
                    WHEN entity_id % 10 < 9 THEN 'setting' ELSE 'page' END,
                CASE WHEN entity_id % 10 < 6 THEN CAST((entity_id * 7919) % 20000 + 1 AS CHAR)
                    WHEN entity_id % 10 < 7 THEN CAST(entity_id % 400 + 1 AS CHAR)
                    WHEN entity_id % 10 < 9 THEN CAST(entity_id % 2000 + 1 AS CHAR)
                    ELSE CAST(entity_id % 300 + 1 AS CHAR) END
            FROM {$journal}
            WHERE correlation_id LIKE '" . self::CORRELATION_PREFIX . "%' AND channel = '" . self::CHANGE_CHANNEL . "'"
        );

        $connection->query(
            'INSERT INTO ' . $this->table(self::FIELD_TABLE) . " (activity_id, field, before_value, after_value,
                is_changed, is_masked)
            SELECT r.activity_id,
                CASE WHEN r.record_type = 'setting'
                    THEN IF(r.activity_id % 997 = 0, '" . self::RARE_PATH . "',
                        CONCAT('section', r.activity_id % 40, '/group', r.activity_id % 7, '/field', s.seq))
                    ELSE ELT(1 + (r.activity_id + s.seq) % 8, 'price', 'name', 'status', 'description',
                        'special_price', 'visibility', 'meta_title', 'qty') END,
                CONCAT('Before ', r.activity_id, IF(r.activity_id % 13 = 0, ' soft cotton shirt', ' plain text')),
                CONCAT('After ', r.activity_id, IF(r.activity_id % 17 = 0, ' organic cotton tee', ' new text')),
                1,
                IF(r.activity_id % 50 = 0, 1, 0)
            FROM " . $this->table(self::RECORD_TABLE) . ' r
            JOIN seq_1_to_3 s ON s.seq <= 2 + r.activity_id % 2'
        );
    }

    /**
     * Remove the seeded journal rows and drop the side tables
     *
     * @return void
     */
    public function remove(): void
    {
        $connection = $this->resourceConnection->getConnection();
        $connection->query('DROP TABLE IF EXISTS ' . $this->table(self::FIELD_TABLE));
        $connection->query('DROP TABLE IF EXISTS ' . $this->table(self::RECORD_TABLE));

        $firstId = $connection->fetchOne(
            $connection->select()
                ->from($this->journalTable(), ['MIN(entity_id)'])
                ->where('correlation_id LIKE ?', self::CORRELATION_PREFIX . '%')
        );
        if (is_numeric($firstId)) {
            $connection->delete($this->journalTable(), [
                'entity_id >= ?' => (int) $firstId,
                'correlation_id LIKE ?' => self::CORRELATION_PREFIX . '%',
            ]);
        }
    }

    /**
     * Id of the item changed most recently, which has changes in any window ending now
     *
     * @return string
     */
    public function recentItem(): string
    {
        $connection = $this->resourceConnection->getConnection();
        $id = $connection->fetchOne(
            $connection->select()
                ->from($this->table(self::RECORD_TABLE), ['record_id'])
                ->where('record_type = ?', 'item')
                ->order('activity_id DESC')
                ->limit(1)
        );

        return is_numeric($id) ? (string) $id : '1';
    }

    /**
     * A side table's name
     *
     * @param string $name
     * @return string
     */
    public function table(string $name): string
    {
        return $this->resourceConnection->getTableName($name);
    }

    /**
     * Seeded journal rows present
     *
     * @return int
     */
    private function seededRows(): int
    {
        $connection = $this->resourceConnection->getConnection();
        $count = $connection->fetchOne(
            $connection->select()
                ->from($this->journalTable(), ['COUNT(*)'])
                ->where('correlation_id LIKE ?', self::CORRELATION_PREFIX . '%')
        );

        return is_numeric($count) ? (int) $count : 0;
    }

    /**
     * Create the side tables when missing
     *
     * @return void
     */
    private function createSideTables(): void
    {
        $connection = $this->resourceConnection->getConnection();
        $connection->query(
            'CREATE TABLE IF NOT EXISTS ' . $this->table(self::RECORD_TABLE) . ' (
                activity_id INT UNSIGNED NOT NULL PRIMARY KEY,
                record_type VARCHAR(64) NOT NULL,
                record_id VARCHAR(64) NULL,
                KEY record (record_type, record_id)
            ) ENGINE=InnoDB'
        );
        $connection->query(
            'CREATE TABLE IF NOT EXISTS ' . $this->table(self::FIELD_TABLE) . ' (
                field_row_id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
                activity_id INT UNSIGNED NOT NULL,
                field VARCHAR(255) NOT NULL,
                before_value MEDIUMTEXT NULL,
                after_value MEDIUMTEXT NULL,
                is_changed TINYINT(1) NOT NULL DEFAULT 0,
                is_masked TINYINT(1) NOT NULL DEFAULT 0,
                KEY activity (activity_id),
                KEY field_activity (field, activity_id)
            ) ENGINE=InnoDB'
        );
    }

    /**
     * The journal table's name
     *
     * @return string
     */
    private function journalTable(): string
    {
        return $this->resourceConnection->getTableName(ActivityResource::TABLE);
    }
}
